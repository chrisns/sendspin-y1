#!/usr/bin/env python3
"""Build the narration script and chapter timings from the guide, and keep the screenshot links honest.

  docs/guide/build.py            resolve screenshots, write SCRIPT.md and chapters.json, report problems
  docs/guide/build.py --check    the same, change nothing, exit 1 on a problem (for CI and pre-commit)

Each chapter file is: front matter (chapter, title), "## Narration" (blockquote lines, spoken), "## On screen" (one line per
shot: `- {{shot:name}}` the first time, which this script turns into an image link whose caption comes from
docs/screenshots/manifest.json, and keeps up to date after that), "## For grown-ups" (documentation only).
"""
import glob, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHOTS = os.path.join(HERE, "..", "screenshots")
WPS = 2.5          # spoken words per second
GAP = 1.2          # seconds of picture after each sentence
LEAD = 1.0


def manifest():
    try:
        return {os.path.splitext(m["file"])[0].split("-", 1)[-1]: m for m in json.load(open(os.path.join(SHOTS, "manifest.json")))}
    except (IOError, ValueError, KeyError):
        return {}


def chapters():
    out = []
    for f in sorted(glob.glob(os.path.join(HERE, "[0-9][0-9]-*.md"))):
        s = open(f).read()
        title = re.search(r"^title: (.*)$", s, re.M).group(1)
        n = int(re.search(r"^chapter: (\d+)$", s, re.M).group(1))
        nar = re.search(r"## Narration\n\n(.*?)\n## ", s, re.S).group(1)
        lines = [re.sub(r"^>\s?", "", l).strip() for l in nar.splitlines() if l.startswith(">") and l[1:].strip()]
        out.append({"file": f, "n": n, "title": title, "narration": lines, "text": s})
    return out


def seconds(lines):
    return LEAD + sum(len(l.split()) / WPS + GAP for l in lines)


def main():
    check = "--check" in sys.argv
    m, problems = manifest(), []
    chs = chapters()
    t, timings, script = 0.0, [], ["# Help video script\n",
        "Generated by `docs/guide/build.py` from the chapters; edit the chapters, not this file. Times are estimates "
        "(2.5 words a second); the real video's `help.json` replaces them.\n"]
    for c in chs:
        new = c["text"]
        def link(mo):
            name = mo.group(1) or mo.group(2)
            shot = m.get(name)
            if not shot:
                problems.append("%s: no screenshot named %r (docs/screenshots/manifest.json)" % (os.path.basename(c["file"]), name))
                return mo.group(0)
            return "![%s](../screenshots/%s) <!-- shot:%s -->" % (shot.get("caption") or shot.get("title") or name, shot["file"], name)
        new = re.sub(r"\{\{shot:([\w-]+)\}\}|!\[[^\]]*\]\([^)]*\) <!-- shot:([\w-]+) -->", link, new)
        if new != c["text"] and not check: open(c["file"], "w").write(new)
        timings.append({"title": c["title"], "start": round(t, 1)})
        script += ["\n## %d. %s  (%d:%02d)\n" % (c["n"], c["title"], t // 60, t % 60)] + ["%s\n" % l for l in c["narration"]]
        t += seconds(c["narration"])
    script.append("\nTotal about %d:%02d.\n" % (t // 60, t % 60))
    if not check:
        open(os.path.join(HERE, "SCRIPT.md"), "w").write("\n".join(script))
        json.dump({"chapters": timings}, open(os.path.join(HERE, "chapters.json"), "w"), indent=1)
    for p in problems: print("problem:", p)
    print("%d chapters, about %d:%02d, %d screenshot links unresolved" % (len(chs), t // 60, t % 60, len(problems)))
    sys.exit(1 if problems and check else 0)


if __name__ == "__main__":
    main()
